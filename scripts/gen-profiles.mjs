// Regenerate src/profiles.generated.ts from the official manifests in ../ace-spec/profiles.
import { readFileSync, writeFileSync } from 'node:fs';
const names = ['core', 'text', 'commerce'];
const src = new URL('../../ace-spec/profiles/', import.meta.url);
let out = '// Generated by scripts/gen-profiles.mjs from ace-spec/profiles/*.json. Do not edit.\n';
out += "import type { ProfileManifest } from './manifest.js';\n\n";
for (const n of names) {
  const json = JSON.parse(readFileSync(new URL(`${n}.json`, src), 'utf8'));
  out += `export const ${n.toUpperCase()}_MANIFEST: ProfileManifest = ${JSON.stringify(json, null, 2)};\n\n`;
}
writeFileSync(new URL('../src/profiles.generated.ts', import.meta.url), out);
